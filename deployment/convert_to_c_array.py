"""
convert_to_c_array.py
=====================
Convert a TFLite flatbuffer (.tflite) into a C header file (model.h)
containing a byte array that can be compiled into ESP32-S3 firmware.

The generated model.h follows the TensorFlow Lite for Microcontrollers
(TFLM) convention:
    const unsigned char g_model[] = { 0x1c, 0x00, ... };
    const unsigned int  g_model_len = XXXX;

Usage:
    python deployment/convert_to_c_array.py
    python deployment/convert_to_c_array.py \
        --input  outputs/model_int8.tflite \
        --output firmware/src/model.h
"""

import os
import sys
import argparse
import logging

logging.basicConfig(level=logging.INFO, format="%(levelname)s | %(message)s")
logger = logging.getLogger(__name__)

OUTPUT_DIR    = os.path.join(os.path.dirname(__file__), "..", "outputs")
FIRMWARE_DIR  = os.path.join(os.path.dirname(__file__), "..", "firmware", "src")
DEFAULT_INPUT  = os.path.join(OUTPUT_DIR,   "model_int8.tflite")
DEFAULT_OUTPUT = os.path.join(FIRMWARE_DIR, "model.h")

BYTES_PER_LINE = 12   # hex bytes per line in the C array


def tflite_to_c_header(
    tflite_path: str,
    header_path: str,
    variable_name: str = "g_model",
) -> None:
    """
    Read a .tflite file and write a C/C++ header with the byte array.

    Parameters
    ----------
    tflite_path   : path to the INT8 .tflite model
    header_path   : output .h file path
    variable_name : C variable name (default: g_model, as expected by TFLM)
    """
    if not os.path.isfile(tflite_path):
        raise FileNotFoundError(
            f"TFLite model not found: {tflite_path}\n"
            "Run deployment/quantize.py first."
        )

    with open(tflite_path, "rb") as f:
        model_bytes = f.read()

    model_len = len(model_bytes)
    logger.info("Model size: %d bytes (%.1f KB)", model_len, model_len / 1024)

    # ── Build hex lines ────────────────────────────────────────────────────────
    hex_lines = []
    for i in range(0, model_len, BYTES_PER_LINE):
        chunk = model_bytes[i:i + BYTES_PER_LINE]
        hex_values = ", ".join(f"0x{b:02x}" for b in chunk)
        hex_lines.append(f"    {hex_values}")

    hex_body = ",\n".join(hex_lines)

    # ── Guard name ─────────────────────────────────────────────────────────────
    guard = os.path.basename(header_path).upper().replace(".", "_").replace("-", "_")

    header_content = f"""\
// ============================================================
// {os.path.basename(header_path)}
// Auto-generated by deployment/convert_to_c_array.py
// DO NOT EDIT MANUALLY
//
// Source : {os.path.basename(tflite_path)}
// Size   : {model_len} bytes ({model_len / 1024:.1f} KB)
// ============================================================

#ifndef {guard}
#define {guard}

// TFLite model data aligned for TFLM tensor arena requirements
alignas(8) const unsigned char {variable_name}[] = {{
{hex_body}
}};

const unsigned int {variable_name}_len = {model_len}u;

#endif  // {guard}
"""

    os.makedirs(os.path.dirname(header_path), exist_ok=True)
    with open(header_path, "w") as fh:
        fh.write(header_content)

    logger.info("C header saved → %s", header_path)
    logger.info("Variable : %s  (%d bytes)", variable_name, model_len)
    logger.info("Include in firmware with:  #include \"model.h\"")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Convert TFLite → C byte array header")
    parser.add_argument("--input",  default=DEFAULT_INPUT,
                        help="Input .tflite model path")
    parser.add_argument("--output", default=DEFAULT_OUTPUT,
                        help="Output .h header path")
    parser.add_argument("--varname", default="g_model",
                        help="C variable name")
    args = parser.parse_args()

    tflite_to_c_header(args.input, args.output, args.varname)
