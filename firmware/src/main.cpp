/*
 * main.cpp
 * ========
 * ESP32-S3 firmware for real-time PPG arrhythmia inference using
 * TensorFlow Lite for Microcontrollers (TFLM).
 *
 * Hardware target : ESP32-S3 (e.g. ESP32-S3-DevKitC-1)
 * Framework       : Arduino (via PlatformIO)
 * TF library      : tflite-micro-arduino-examples
 *
 * PPG input       : 10 s window of 1250 samples (125 Hz) normalised to [0,1]
 * Model output    : Softmax probabilities over 5 arrhythmia classes
 *
 * Serial output (115200 baud):
 *   [Inference #1] Class: Normal (0)  Confidence: 0.9412
 *
 * To replace the dummy ADC with a real sensor (e.g. MAX30102):
 *   1. Wire sensor to I2C (SDA=GPIO8, SCL=GPIO9) or SPI
 *   2. Install a driver library (e.g. sparkfun/SparkFun_MAX3010x_Sensor_Library)
 *   3. Replace fill_ppg_window() with real ADC reads
 */

// ── TensorFlow Lite for Microcontrollers ──────────────────────────────────────
#include "tensorflow/lite/micro/micro_interpreter.h"
#include "tensorflow/lite/micro/micro_mutable_op_resolver.h"
#include "tensorflow/lite/micro/system_setup.h"
#include "tensorflow/lite/schema/schema_generated.h"

// ── Model byte array (auto-generated by deployment/convert_to_c_array.py) ────
#include "model.h"

// ── Arduino runtime ───────────────────────────────────────────────────────────
#include <Arduino.h>
#include <math.h>

// ─────────────────────────────────────────────────────────────────────────────
//  CONFIGURATION
// ─────────────────────────────────────────────────────────────────────────────
static constexpr int   kInputLength   = 1250;   // samples per window
static constexpr int   kNumClasses    = 5;
static constexpr int   kInferenceHz   = 1;      // run inference once per second
static constexpr float kSampleRateHz  = 125.0f; // PPG sampling rate

// Tensor arena size – tune if you get kTfLiteError on AllocateTensors()
// ESP32-S3 has 512 KB SRAM; 256 KB is a safe starting point for this model.
static constexpr int kTensorArenaSize = 256 * 1024;  // 256 KB

// ─────────────────────────────────────────────────────────────────────────────
//  TFLM globals
// ─────────────────────────────────────────────────────────────────────────────
alignas(16) static uint8_t tensor_arena[kTensorArenaSize];

static const tflite::Model*         model_ptr   = nullptr;
static tflite::MicroInterpreter*    interpreter = nullptr;
static TfLiteTensor*                input       = nullptr;
static TfLiteTensor*                output      = nullptr;

// Op resolver – add only the ops your model uses to minimise flash usage
static tflite::MicroMutableOpResolver<10> op_resolver;

// ─────────────────────────────────────────────────────────────────────────────
//  Class labels (must match training label_mapping.py)
// ─────────────────────────────────────────────────────────────────────────────
static const char* kClassNames[kNumClasses] = {
    "Normal",
    "Atrial Fibrillation",
    "Bradycardia",
    "Tachycardia",
    "Other Arrhythmia",
};

// ─────────────────────────────────────────────────────────────────────────────
//  PPG WINDOW BUFFER
//  In production: fill this buffer with real ADC samples from your PPG sensor.
//  Here we use a synthetic 1.2 Hz sine wave + small noise as a placeholder.
// ─────────────────────────────────────────────────────────────────────────────
static float ppg_window[kInputLength];

/**
 * fill_ppg_window()
 * -----------------
 * PLACEHOLDER: Replace with real ADC reads from a MAX30102/MAX30101 sensor.
 *
 * The function generates a synthetic PPG-like waveform:
 *   - Fundamental at 1.2 Hz (72 bpm)
 *   - Harmonic at 2.4 Hz
 *   - Small Gaussian noise
 *
 * The window is min-max normalised to [0.0, 1.0] to match training.
 */
void fill_ppg_window() {
    const float TWO_PI = 2.0f * M_PI;
    const float hr_hz  = 1.2f;  // 72 bpm

    float min_val =  1e9f;
    float max_val = -1e9f;

    for (int i = 0; i < kInputLength; i++) {
        float t = (float)i / kSampleRateHz;
        // Synthetic PPG: fundamental + 2nd harmonic + noise
        float noise = 0.03f * sinf(TWO_PI * 53.7f * t + 0.3f);  // high-freq noise proxy
        ppg_window[i] = 0.7f * sinf(TWO_PI * hr_hz * t)
                      + 0.2f * sinf(TWO_PI * 2.0f * hr_hz * t + 0.8f)
                      + noise;

        if (ppg_window[i] < min_val) min_val = ppg_window[i];
        if (ppg_window[i] > max_val) max_val = ppg_window[i];
    }

    // Normalise to [0, 1]
    float rng = max_val - min_val;
    if (rng < 1e-6f) rng = 1.0f;
    for (int i = 0; i < kInputLength; i++) {
        ppg_window[i] = (ppg_window[i] - min_val) / rng;
    }
}

// ─────────────────────────────────────────────────────────────────────────────
//  Quantisation helpers
// ─────────────────────────────────────────────────────────────────────────────

/**
 * Quantise a float value to int8 using the tensor's scale/zero_point.
 * Required because the TFLite model uses INT8 input/output.
 */
inline int8_t float_to_int8(float value, float scale, int32_t zero_point) {
    int32_t quant = (int32_t)(roundf(value / scale)) + zero_point;
    if (quant < -128) quant = -128;
    if (quant >  127) quant =  127;
    return (int8_t)quant;
}

inline float int8_to_float(int8_t value, float scale, int32_t zero_point) {
    return scale * ((float)value - (float)zero_point);
}

// ─────────────────────────────────────────────────────────────────────────────
//  SETUP
// ─────────────────────────────────────────────────────────────────────────────
void setup() {
    Serial.begin(115200);
    delay(500);  // allow USB-CDC to connect

    Serial.println("\n========================================");
    Serial.println("  PPG Arrhythmia Inference – ESP32-S3");
    Serial.println("========================================\n");

    // ── 1. Load model ──────────────────────────────────────────────────────
    model_ptr = tflite::GetModel(g_model);
    if (model_ptr->version() != TFLITE_SCHEMA_VERSION) {
        Serial.printf("ERROR: Model schema version %d != runtime %d\n",
                      model_ptr->version(), TFLITE_SCHEMA_VERSION);
        while (true) {}  // halt
    }

    // ── 2. Register ops (match what your model uses) ───────────────────────
    op_resolver.AddConv2D();          // fallback for Conv1D → Conv2D in TFLM
    op_resolver.AddDepthwiseConv2D();
    op_resolver.AddFullyConnected();
    op_resolver.AddSoftmax();
    op_resolver.AddReshape();
    op_resolver.AddMaxPool2D();
    op_resolver.AddUnidirectionalSequenceLSTM();
    op_resolver.AddQuantize();
    op_resolver.AddDequantize();
    op_resolver.AddMul();

    // ── 3. Build interpreter ───────────────────────────────────────────────
    static tflite::MicroInterpreter static_interpreter(
        model_ptr, op_resolver, tensor_arena, kTensorArenaSize);
    interpreter = &static_interpreter;

    TfLiteStatus alloc_status = interpreter->AllocateTensors();
    if (alloc_status != kTfLiteOk) {
        Serial.println("ERROR: AllocateTensors() failed! Increase kTensorArenaSize.");
        while (true) {}
    }

    // ── 4. Get I/O pointers ────────────────────────────────────────────────
    input  = interpreter->input(0);
    output = interpreter->output(0);

    Serial.printf("Input  tensor: [%d, %d, %d] dtype=%d\n",
                  input->dims->data[0], input->dims->data[1],
                  input->dims->data[2], input->type);
    Serial.printf("Output tensor: [%d, %d] dtype=%d\n",
                  output->dims->data[0], output->dims->data[1], output->type);
    Serial.printf("Tensor arena used: %u / %d bytes\n\n",
                  interpreter->arena_used_bytes(), kTensorArenaSize);

    Serial.println("Initialisation complete. Starting inference loop …\n");
}

// ─────────────────────────────────────────────────────────────────────────────
//  LOOP
// ─────────────────────────────────────────────────────────────────────────────
static uint32_t inference_count = 0;

void loop() {
    unsigned long t_start = millis();

    // ── Step 1: Acquire PPG window ─────────────────────────────────────────
    fill_ppg_window();  // replace with real ADC read in production

    // ── Step 2: Quantise and fill input tensor ─────────────────────────────
    float  inp_scale      = input->params.scale;
    int32_t inp_zero_point = input->params.zero_point;

    int8_t* inp_data = input->data.int8;
    for (int i = 0; i < kInputLength; i++) {
        inp_data[i] = float_to_int8(ppg_window[i], inp_scale, inp_zero_point);
    }

    // ── Step 3: Run inference ──────────────────────────────────────────────
    TfLiteStatus invoke_status = interpreter->Invoke();
    if (invoke_status != kTfLiteOk) {
        Serial.println("ERROR: Invoke() failed!");
        delay(1000);
        return;
    }

    // ── Step 4: Dequantise output probabilities ────────────────────────────
    float  out_scale       = output->params.scale;
    int32_t out_zero_point = output->params.zero_point;

    float probs[kNumClasses];
    int8_t* out_data = output->data.int8;
    int    top_class  = 0;
    float  top_prob   = -1.0f;

    for (int c = 0; c < kNumClasses; c++) {
        probs[c] = int8_to_float(out_data[c], out_scale, out_zero_point);
        if (probs[c] > top_prob) {
            top_prob  = probs[c];
            top_class = c;
        }
    }

    // ── Step 5: Report result via Serial ──────────────────────────────────
    inference_count++;
    unsigned long elapsed = millis() - t_start;

    Serial.printf("[Inference #%lu | %lums]\n", inference_count, elapsed);
    Serial.printf("  Prediction : %-22s (class %d)\n",
                  kClassNames[top_class], top_class);
    Serial.printf("  Confidence : %.4f (%.1f%%)\n", top_prob, top_prob * 100.0f);
    Serial.println("  All classes:");
    for (int c = 0; c < kNumClasses; c++) {
        Serial.printf("    [%d] %-22s : %.4f\n", c, kClassNames[c], probs[c]);
    }
    Serial.println();

    // ── Pacing: run inference once every second ────────────────────────────
    unsigned long loop_ms = millis() - t_start;
    if (loop_ms < (1000u / kInferenceHz)) {
        delay((1000u / kInferenceHz) - loop_ms);
    }
}
